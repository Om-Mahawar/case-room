/** Writes docs/VERIFICATION.md from the skeleton files, so the record cannot drift from the data. */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadSkeletons } from "../src/schema/load";

const order = ["profitability", "market_entry", "pricing", "growth", "m_and_a", "guesstimate", "operations", "unconventional"];
const all = loadSkeletons().sort((a, b) => order.indexOf(a.type) - order.indexOf(b.type) || (a.runMode === b.runMode ? a.id.localeCompare(b.id) : a.runMode === "full" ? -1 : 1));
const flagCount = all.reduce((n, s) => n + s.verifierFlags.length, 0);
const out: string[] = [];
out.push("# Verification record");
out.push("");
out.push("Generated by `scripts/build-verification.ts` from the skeleton files. Do not edit by hand.");
out.push("");
out.push("## What was checked");
out.push("");
out.push("On 12 Nov 2026 Claude re-read each of the 16 draft skeletons against the column-corrected text of its casebook pages and checked, line by line:");
out.push("");
out.push("- every entry in the fact sheet is something the **interviewer** says in the source, with the same figure;");
out.push("- every figure the **candidate** proposed sits under accepted assumptions, not facts;");
out.push("- the arithmetic in every quant moment, recomputed;");
out.push("- the crux, clue and close against how the source case actually turns;");
out.push("- each open verifier point, with a decision recorded.");
out.push("");
out.push("## Result");
out.push("");
out.push(`No factual error was found in the 16 drafts. ${flagCount} verifier points were settled; the decisions are below and in each file's \`verifierFlags\`. Four changes were made on the way: the Vistara case was reset as an unnamed airline and run as a drill, with the book's unsupported ₹30,000 ceiling dropped; the post-merger case's ambiguous revenue line was fixed to one reading; the cough-syrup company is "mid-sized" only; and interviewer probes from the transcripts were added to several cases.`);
out.push("");
out.push("## What this check is not");
out.push("");
out.push("It is a second pass by the same model that drafted the skeletons, not an independent check by a person who has interviewed. It can confirm that a skeleton matches its page. It cannot confirm that the crux is what a real interviewer would test, or that the anchors separate a 7 from a 9 the way a human would. The specification's human check (about 15 minutes a case) and the calibration run (T-CAL) are still due before students rely on the scores. Until then every case is labelled **AI-checked**.");
out.push("");
out.push("## The 16 skeletons");
out.push("");
out.push("| Skeleton | Type | Source | Confidence | Runs as | Facts | Quant |");
out.push("| --- | --- | --- | --- | --- | --- | --- |");
for (const s of all) {
  const probes = s.facts.filter((f) => f.kind === "probe").length;
  const clues = s.facts.filter((f) => f.kind === "clue").length;
  const plain = s.facts.length - probes - clues;
  out.push(`| \`${s.id}\` | ${s.type.replace(/_/g, " ")} | ${s.source.book.split(",")[0]}, p${s.source.pages} | ${s.confidence} | ${s.runMode === "drill" ? "drill" : "full case"} | ${plain} facts, ${clues} clues, ${probes} probes | ${s.quant.kind}${s.quant.optional ? " (optional)" : ""} |`);
}
out.push("");
out.push("## Decisions on the verifier points");
for (const s of all) {
  out.push("");
  out.push(`### ${s.title} (\`${s.id}\`)`);
  out.push("");
  for (const f of s.verifierFlags) out.push(`- **Point:** ${f.text}\n  **Decision:** ${f.decision ?? "(open)"}`);
}
out.push("");
writeFileSync(join(process.cwd(), "docs", "VERIFICATION.md"), out.join("\n"));
console.log(`docs/VERIFICATION.md: ${all.length} skeletons, ${flagCount} decisions`);
