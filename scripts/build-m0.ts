/** Writes m0/data.js so the probe page runs from a file with no build step and no fetch of local files. */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadSkeletons, skeletonAllowedNumbers } from "../src/schema/load";
import { interviewerView, INTERVIEWER_TURN_SCHEMA } from "../src/engine/skeletonView";
import { OUT_OF_SCOPE_REPLY } from "../src/schema/skeleton";

const s = loadSkeletons().find((x) => x.id === "iima-abc-batteries");
if (!s) throw new Error("iima-abc-batteries not found");
const rules = readFileSync(join(process.cwd(), "prompts", "interviewer.md"), "utf8").trim();
const data = {
  builtFrom: { skeleton: s.id, skeletonVersion: s.version },
  system: `${rules}\n\n${interviewerView(s)}`,
  prompt: s.prompt,
  schema: INTERVIEWER_TURN_SCHEMA,
  allowedNumbers: [...skeletonAllowedNumbers(s)],
  outOfScopeReply: OUT_OF_SCOPE_REPLY,
  clueIds: s.facts.filter((f) => f.kind === "clue").map((f) => f.id),
  priceFactId: s.facts.find((f) => /price compared/i.test(f.asks))?.id ?? "",
};
if (!data.priceFactId) throw new Error("price fact not found");
writeFileSync(join(process.cwd(), "m0", "data.js"), `// Generated by scripts/build-m0.ts. Do not edit.\nwindow.M0_DATA = ${JSON.stringify(data, null, 2)};\n`);
console.log(`m0/data.js written (${data.system.length} characters of system prompt, about ${Math.round(data.system.length / 4)} tokens)`);
